const allReports = []
  .concat(collect.reports || [])
  .concat(refresh.reports || [])
  .concat(scan.reports || []);

return {
  date: date,
  stages: {
    collect: { status: collect.status, summary: collect.summary },
    refresh: { status: refresh.status, summary: refresh.summary },
    scan: { status: scan.status, summary: scan.summary }
  },
  reports: allReports
};